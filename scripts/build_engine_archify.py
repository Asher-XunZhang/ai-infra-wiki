ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / "pages/engine-comparison/diagrams"
IMAGES = ROOT / "images/engine-comparison"
BUNDLE = ROOT / "pages/engine-comparison/archify-assets.js"
