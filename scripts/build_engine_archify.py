"""Import checked Archify SVGs; verify the frozen source/SVG/runtime bundle in CI.

Archify is an authoring tool, not a browser dependency. Its native HTML and
browser receipts stay in the authoring directory; Pages loads canonical SVG
geometry and lets the lesson own selection and the single pulse clock.
"""
