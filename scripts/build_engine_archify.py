def sha(data):
    return hashlib.sha256(data).hexdigest()


def canonical_svg(html):
    start = re.search(r'<svg\s+viewBox="', html)
    if not start:
        raise ValueError("Archify canonical SVG is missing")
    svg = html[start.start():html.index("</svg>", start.start()) + 6]
    svg = re.sub(r"<style>.*?</style>", "", svg, flags=re.S)
    svg = svg.replace("<svg ", '<svg xmlns="http://www.w3.org/2000/svg" ', 1)
    svg = svg.replace("<!-- Definitions -->", "<style>" + STYLE + "</style><!-- Definitions -->", 1)
    svg = "\n".join(line.rstrip() for line in svg.splitlines())
    ET.fromstring(svg)
    return svg


def compile_bundle(manifest):
    assets = {}
    for key, receipt in sorted(manifest["diagrams"].items()):
        source = json.loads((SOURCES / (key + ".json")).read_text())
        svg = (IMAGES / (key + ".svg")).read_text()
        nodes = source.get("components", source.get("participants", source.get("states", source.get("nodes", []))))
        edges = source.get("connections", source.get("messages", source.get("transitions", source.get("flows", source.get("edges", [])))))
        assets[key] = {"svg": svg, "type": source["diagram_type"], "title": source["meta"]["title"],
                       "repository": source["meta"]["repository"], "nodes": nodes, "edges": edges}
    return "/* Generated by scripts/build_engine_archify.py; do not edit. */\nwindow.AtlasArchifyAssets = " + json.dumps(assets, ensure_ascii=False, separators=(",", ":")) + ";\n"


def build(import_dir=None, check=False):
    if import_dir:
        IMAGES.mkdir(parents=True, exist_ok=True)
        manifest = {"schema": 1, "generator": "Archify 3.3", "diagrams": {}}
        for source in sorted(SOURCES.glob("*.json")):
            if source.name in ("generated.json", "locales.json"):
                continue
            key = source.stem
            spec = json.loads(source.read_text())
            html = (import_dir / spec["meta"]["output"]).read_bytes()
            receipts = list(import_dir.rglob(key + ".finalize-summary.json"))
            passing = []
            for path in receipts:
                value = json.loads(path.read_text())
                if (value.get("ok") and value["specification"]["sha256"] == sha(source.read_bytes())
                        and value["artifact"]["sha256"] == sha(html)
                        and all(value["gates"].get(gate) == "pass" for gate in ("validate", "deliver", "check", "browser-check"))):
                    passing.append(value)
            if not passing:
                raise ValueError(f"{key}: no passing Archify receipt for these exact source/artifact bytes")
            svg = canonical_svg(html.decode())
            (IMAGES / (key + ".svg")).write_text(svg + "\n")
            manifest["diagrams"][key] = {"sourceSha256": sha(source.read_bytes()), "svgSha256": sha((svg + "\n").encode()),
                                              "nativeHtmlSha256": sha(html), "gates": passing[-1]["gates"]}
        MANIFEST.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
        BUNDLE.write_text(compile_bundle(manifest))
    manifest = json.loads(MANIFEST.read_text())
    for key, item in manifest["diagrams"].items():
        assert all(item["gates"].get(gate) == "pass" for gate in ("validate", "deliver", "check", "browser-check")), f"{key}: missing passing Archify gate"
        assert sha((SOURCES / (key + ".json")).read_bytes()) == item["sourceSha256"], f"{key}: source changed; regenerate with Archify"
        assert sha((IMAGES / (key + ".svg")).read_bytes()) == item["svgSha256"], f"{key}: SVG differs from checked import"
    current = {p.stem for p in SOURCES.glob("*.json") if p.name not in ("generated.json", "locales.json")}
    assert current == set(manifest["diagrams"]), "Archify source catalog and generated diagrams differ"
    expected = compile_bundle(manifest)
    if check:
        assert BUNDLE.read_text() == expected, "Archify runtime bundle is stale"
    else:
        BUNDLE.write_text(expected)
    return len(manifest["diagrams"])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--import-dir", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    print(f"Archify source/SVG/runtime consistency: {build(args.import_dir, args.check)} diagrams")
